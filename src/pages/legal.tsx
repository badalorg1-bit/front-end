/** Date shown as "last updated" on both legal pages. */
const UPDATED = "11 نوفمبر 2026";

type Section = { title: string; content: ReactNode };

function LegalPage({
  title,
  subtitle,
  icon,
  sections,
}: {
  title: string;
  subtitle: string;
  icon: typeof FileText;
  sections: Section[];
}) {
  const Icon = icon;
  return (
    <div className="mx-auto max-w-3xl px-4 py-10">
      <div className="flex items-start gap-3">
        <span
          aria-hidden
          className="flex size-10 shrink-0 items-center justify-center rounded-xl bg-brand/10 text-brand"
        >
          <Icon className="size-5" />
        </span>
        <div>
          <h1 className="text-2xl font-bold text-ink">{title}</h1>
          <p className="mt-1 text-xs text-ink-muted">آخر تحديث: {UPDATED}</p>
          <p className="mt-2 text-sm leading-7 text-ink-muted">{subtitle}</p>
        </div>
      </div>

      <ol className="mt-6 space-y-4">
        {sections.map((s, i) => (
          <li key={s.title} className="rounded-xl border border-line bg-card p-5">
            <h2 className="flex items-center gap-2 text-base font-bold text-ink">
              <span
                aria-hidden
                className="flex size-6 shrink-0 items-center justify-center rounded-full bg-brand/10 text-xs font-bold text-brand"
              >
                {i + 1}
              </span>
              {s.title}
            </h2>
            <div className="mt-3 space-y-2 text-sm leading-7 text-ink-muted">{s.content}</div>
          </li>
        ))}
      </ol>

      <p className="mt-6 rounded-xl border border-line bg-secondary/60 p-4 text-sm leading-7 text-ink-muted">
        لأي استفسار راجع{" "}
        <Link to="/support" className="font-medium text-brand hover:underline">
          صفحة الدعم والشكاوى
        </Link>{" "}
        أو عد إلى{" "}
        <Link to="/" className="font-medium text-brand hover:underline">
          الرئيسية
        </Link>
        .
      </p>
    </div>
  );
}

function Bullets(items: ReactNode[]) {
  return (
    <ul className="list-disc space-y-1.5 ps-5">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  );
}

